    def _match_template_fields_3step(self, ws) -> Dict[str, int]:
        """匹配模板列标题 -> 模板标准字段名（3-step JSON路径使用）

        返回 {标准字段名: 列号}，如 {"Severity": 10, "Rationale Severity": 11, ...}
        字段名对应 STEP3_TO_STANDARD 的键，用于从 3-step JSON context 中查找数据。

        匹配优先级（按 Row4 → Row5 单字母 → Row5 子标题的顺序）：
          1. Row5 单字母 (S/E/C/HZ-ID/SG-ID)  -> 标准字段名（精确匹配）
          2. Row4 主标题 -> 标准字段名（精确或子集匹配）
          3. Row5 子标题 -> 标准字段名（精确或子集匹配）
        这样确保 "Rationale Severity" 不会错误匹配 Row4 的 "Severity (S)"。
        """
        mapping = {}

        def n(s):
            return re.sub(r'\s+', ' ', str(s or '')).strip().lower()

        SINGLE_LETTER = {
            's': 'Severity',
            'e': 'Exposure',
            'c': 'Controllability',
            'hz-id': 'HZ-ID',
            'sg-id': 'SG-ID',
        }

        for col_idx in range(1, ws.max_column + 1):
            row4 = n(str(ws.cell(4, col_idx).value or ''))
            row5 = n(str(ws.cell(5, col_idx).value or ''))

            if row5 in SINGLE_LETTER:
                mapping[SINGLE_LETTER[row5]] = col_idx
                continue

            if row5:
                matched_exact = next(
                    (sn for sn in self.STEP3_TO_STANDARD if n(sn) == row5), None
                )
                if matched_exact:
                    mapping[matched_exact] = col_idx
                    continue

                s5_words = set(row5.split())
                best_subset = None
                best_word_count = 0
                for std_name in self.STEP3_TO_STANDARD:
                    std_words = set(n(std_name).split())
                    if std_words and std_words.issubset(s5_words):
                        wc = len(std_words)
                        if wc > best_word_count:
                            best_word_count = wc
                            best_subset = std_name
                if best_subset:
                    mapping[best_subset] = col_idx
                    continue

            if row4:
                matched_exact = next(
                    (sn for sn in self.STEP3_TO_STANDARD if n(sn) == row4), None
                )
                if matched_exact:
                    mapping[matched_exact] = col_idx
                    continue

                s4_words = set(row4.split())
                best_subset = None
                best_word_count = 0
                for std_name in self.STEP3_TO_STANDARD:
                    std_words = set(n(std_name).split())
                    if std_words and std_words.issubset(s4_words):
                        wc = len(std_words)
                        if wc > best_word_count:
                            best_word_count = wc
                            best_subset = std_name
                if best_subset:
                    mapping[best_subset] = col_idx

        if 9 not in mapping.values():
            mapping["Hazardous event"] = 9

        return mapping

    def _get_experience_col_mapping(self, ws, experience_data: Dict[str, Any]) -> Dict[str, int]:
        """经验库JSON路径的列映射：经验库JSON字段 -> 模板列号

        返回 {经验库JSON字段名: 列号}，如 {"Severity": 10, "ASIL": 17, ...}

        匹配优先级（确保每个字段只匹配到一列）：
        1. 行5单字母 S/E/C/HZ-ID/SG-ID -> 对应字段（最高优先级）
        2. 行5/行4 精确匹配 JSON字段名
        3. 行5/行4 子集匹配（仅在精确匹配失败时）
        4. EXP2字段（EXPERIENCE_TO_STANDARD）的标准列位置兜底

        经验库文件结构（HARA_Template标准 21列）：
        col 10=row5=S, col11=行5子标题 -> S在row5精确匹配 "Severity"
        col 11=row5=行5子标题 -> 不能被子集匹配到"Severity"（在步骤2会精确匹配"理性严重性评估"）
        """
        mapping = {}
        raw = experience_data.get("raw", {})
        hara_rows = experience_data.get("05_HARA", raw.get("05_HARA", []))
        json_keys = set()
        for row in hara_rows:
            json_keys.update(row.keys())
            break

        def n(s):
            return re.sub(r'\s+', ' ', str(s or '')).strip().lower()

        def read_headers(ws):
            h4 = {}
            h5 = {}
            for c in range(1, ws.max_column + 1):
                v4 = ws.cell(4, c).value
                v5 = ws.cell(5, c).value
                h4[c] = n(str(v4)) if v4 is not None else ''
                h5[c] = n(str(v5)) if v5 is not None else ''
            return h4, h5

        h4, h5 = read_headers(ws)

        offset = 0
        for c in range(1, ws.max_column + 1):
            if h5[c] == 'hara-id' or (h4[c] == 'hara-id' and h5[c] == ''):
                offset = c - 1
                break

        template_col_shift = 0
        if ws.max_column > 21:
            if h4.get(18) == '' and h5.get(18) == 'hz-id':
                template_col_shift = 2

        def col(n):
            return n + offset + template_col_shift

        exp2_fallback_uses_col = True
        if template_col_shift > 0:
            exp2_fallback_uses_col = False

        STANDARD_POS = {
            'HARA-ID': col(1), 'Function': col(2), 'Output': col(3),
            'Guide-Word': col(4), 'Malfunction': col(5), 'Hazard': col(6),
            'Situational description': col(7), 'Situational detailing': col(8),
            'Potential damage': col(9), 'Hazardous event': col(9),
            'Severity': col(10), 'Severity_Rationale': col(11),
            'Exposure': col(12), 'Exposure_TF': col(13), 'Exposure_Rationale': col(14),
            'Controllability': col(15), 'Controllability_Rationale': col(16),
            'ASIL': col(17), 'SG-ID': col(18), 'Safety Goal': col(19),
            'Safe state': col(20), 'Remark': col(21),
            'FTTI': col(22), 'FTTI_Basis': col(23),
        }

        if template_col_shift > 0:
            for k in list(STANDARD_POS.keys()):
                STANDARD_POS[k] -= template_col_shift

        SINGLE_LETTER = {
            's': 'Severity', 'e': 'Exposure', 'c': 'Controllability',
            'hz-id': 'HZ-ID', 'sg-id': 'SG-ID',
        }

        def match_exact(hdr, keys):
            for k in keys:
                if n(k) == hdr:
                    return k
            return None

        def match_subset(hdr, keys, min_words=2):
            hdr_words = set(hdr.split())
            for k in keys:
                k_words = set(n(k).split())
                if k_words and k_words.issubset(hdr_words) and len(k_words) >= min_words:
                    return k
            return None

        for col_idx in range(1, ws.max_column + 1):
            h5v = h5[col_idx]
            h4v = h4[col_idx]

            if not h5v and not h4v:
                continue

            matched = None

            if h5v in SINGLE_LETTER:
                matched = SINGLE_LETTER[h5v]
            elif h5v:
                matched = match_exact(h5v, json_keys)
                if not matched:
                    matched = match_subset(h5v, json_keys, min_words=2)
                if matched:
                    mapping[matched] = col_idx
                    continue

            if not matched and h4v:
                matched = match_exact(h4v, json_keys)
                if not matched:
                    matched = match_subset(h4v, json_keys, min_words=2)
                if matched:
                    mapping[matched] = col_idx
                    continue

        for exp_key, std_name in self.EXPERIENCE_TO_STANDARD.items():
            if exp_key not in mapping:
                if std_name in STANDARD_POS:
                    if exp2_fallback_uses_col:
                        std_col = STANDARD_POS[std_name]
                    else:
                        std_col = STANDARD_POS[std_name]
                        if std_name in ('HZ-ID', 'SG-ID', 'Safety Goal', 'Safe state'):
                            std_col = STANDARD_POS[std_name] + template_col_shift
                    if std_col <= ws.max_column:
                        mapping[exp_key] = std_col

        return mapping
    
