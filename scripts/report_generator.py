    def _extract_malfunction_from_key(self, key):
        """从function_scenarios的key中提取malfunction描述。

        JSON中key可能是string representation of dict，例如:
        "{'guideword': 'unintended', 'malfunction': '非预期触发CEA-0768', ...}"
        也可能是正常的malfunction_desc字符串。
        """
        if isinstance(key, dict):
            return key.get("malfunction", "")
        if isinstance(key, str):
            key_stripped = key.strip()
            if key_stripped.startswith("{"):
                import ast
                try:
                    parsed = ast.literal_eval(key_stripped)
                    if isinstance(parsed, dict):
                        return parsed.get("malfunction", key_stripped)
                except (ValueError, SyntaxError):
                    pass
            if key_stripped and len(key_stripped) > 0:
                return key_stripped
        return ""

