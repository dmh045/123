    def _merge_duplicate_static_cells(self, ws, start_row: int, end_row: int):
        """按字段层级合并连续重复的静态列，动态风险结果保持逐行独立。"""
        hierarchy = {
            2: (),             # Function
            3: (2,),           # Output, within Function
            4: (2, 3),         # Guideword, within Function/Output
            5: (2, 3, 4),      # Malfunction, within Guideword
            6: (2, 3, 4, 5),   # Hazard, within Malfunction
            7: (2, 3, 4, 5, 6),  # Identical situation, within the same hazard
        }
        snapshot = {
            row: {col: ws.cell(row, col).value for col in range(2, 8)}
            for row in range(start_row, end_row + 1)
        }
        for col, parent_cols in hierarchy.items():
            group_start = start_row
            previous_key = (
                tuple(snapshot[start_row][parent] for parent in parent_cols),
                snapshot[start_row][col],
            )
            for row in range(start_row + 1, end_row + 2):
                current_key = object()
                if row <= end_row:
                    current_key = (
                        tuple(snapshot[row][parent] for parent in parent_cols),
                        snapshot[row][col],
                    )
                if current_key != previous_key:
                    previous = previous_key[1]
                    if previous not in (None, "") and row - group_start > 1:
                        ws.merge_cells(
                            start_row=group_start, start_column=col,
                            end_row=row - 1, end_column=col,
                        )
                        ws.cell(group_start, col).alignment = self.styles["center_alignment"]
                    group_start = row
                    previous_key = current_key

    def _fill_safety_goal_sheet_from_hara(
        self, ws_sg, ws_hara, start_row: int, end_row: int,
        safety_goal_catalog: Optional[Dict[str, Any]] = None,
    ) -> Dict[str, Any]:
        """从 05_HARA 的非 QM 记录生成 06_Safety Goal，并按 SG-ID 取最高 ASIL。"""
        try:
            asil_rank = {"QM": 0, "A": 1, "ASIL A": 1, "B": 2, "ASIL B": 2,
                         "C": 3, "ASIL C": 3, "D": 4, "ASIL D": 4}
            goals = {}
            for row in range(start_row, end_row + 1):
                asil = str(ws_hara.cell(row, 17).value or "").strip()
                sg_id = str(ws_hara.cell(row, 18).value or "").strip()
                if asil_rank.get(asil.upper(), asil_rank.get(asil, 0)) == 0 or sg_id in ("", "NA", "N/A"):
                    continue
                item = {
                    "Hazards": [],
                    "SG-ID": sg_id,
                    "Safety Goal": ws_hara.cell(row, 19).value,
                    "Safety State": ws_hara.cell(row, 20).value,
                    "Max.ASIL": asil,
                    "FTTI": ws_hara.cell(row, 22).value,
                    "FTTI Basis": ws_hara.cell(row, 23).value,
                }
                hazard = ws_hara.cell(row, 6).value
                old = goals.get(sg_id)
                if old is None:
                    goals[sg_id] = item
                    old = item
                if hazard not in (None, "") and hazard not in old["Hazards"]:
                    old["Hazards"].append(hazard)
                if asil_rank.get(asil.upper(), asil_rank.get(asil, 0)) > asil_rank.get(str(old["Max.ASIL"]).upper(), 0):
                    old["Max.ASIL"] = asil
                new_ftti = re.search(r"\d+(?:\.\d+)?", str(item.get("FTTI") or ""))
                old_ftti = re.search(r"\d+(?:\.\d+)?", str(old.get("FTTI") or ""))
                if new_ftti and (not old_ftti or float(new_ftti.group()) < float(old_ftti.group())):
                    old["FTTI"] = item["FTTI"]
                    old["FTTI Basis"] = item["FTTI Basis"]

            for sg_id, item in goals.items():
                catalog_entry = (safety_goal_catalog or {}).get(sg_id, {})
                if catalog_entry:
                    item["FTTI"] = catalog_entry.get("ftti_requirement", "NEEDS_REVIEW")
                    status = catalog_entry.get("ftti_status", "NEEDS_REVIEW")
                    item["FTTI Basis"] = f"{catalog_entry.get('ftti_basis', 'FTTI待评审')} [Status={status}]"

            first_row = 4
            required_end = first_row + len(goals) - 1
            for row in range(first_row, max(ws_sg.max_row, required_end) + 1):
                for col in range(1, 9):
                    ws_sg.cell(row, col).value = None

            for index, sg_id in enumerate(sorted(goals), 1):
                item = goals[sg_id]
                row = first_row + index - 1
                hz_id = sg_id.replace("SG_", "HZ_", 1)
                values = [hz_id, "\n".join(str(value) for value in item["Hazards"]), item["SG-ID"],
                          item["Safety Goal"], item["Safety State"], item["Max.ASIL"],
                          item["FTTI"], item["FTTI Basis"]]
                for col, value in enumerate(values, 1):
                    self._set_cell(ws_sg, row, col, value, 0)
                ws_sg.row_dimensions[row].height = 60
            return {"success": True, "filled_rows": len(goals)}
        except Exception as exc:
            return {"success": False, "error": str(exc)}
    
