    def _load_template_headers(self, template_path: str = None):
        """从模板动态加载列标题映射（3-step路径使用）

        返回 {标准字段名: 列号}，用于 _fill_hara_sheet() 从 3-step JSON context 写入数据。
        """
        path = template_path or self.template_path
        try:
            wb = openpyxl.load_workbook(path)
            ws = wb[self.HARA_SHEET_NAME]

            self._header_row_4 = {}
            self._header_row_5 = {}

            for col_idx in range(1, ws.max_column + 1):
                val_4 = ws.cell(row=4, column=col_idx).value
                val_5 = ws.cell(row=5, column=col_idx).value

                if val_4:
                    self._header_row_4[col_idx] = str(val_4).replace('\n', ' ').strip()
                if val_5:
                    self._header_row_5[col_idx] = str(val_5).replace('\n', ' ').strip()

            self._verify_template_structure(ws)

            self._column_mapping = self._match_template_fields_3step(ws)

            logger.info(f"模板标题加载完成: {len(self._column_mapping)} 个列")

            unmatched = [k for k in self.HARA_TEMPLATE_COLUMNS.values() if k not in self._column_mapping]
            if unmatched:
                logger.info(f"未匹配的模板字段: {unmatched}")

            wb.close()

        except Exception as e:
            logger.warning(f"加载模板标题失败: {e}，使用标准列映射")
            if os.path.exists(path):
                self._column_mapping = {v: k for k, v in self.HARA_TEMPLATE_COLUMNS.items()}
            else:
                logger.warning(f"模板文件不存在: {path}，跳过列映射初始化")
    
    def _verify_template_structure(self, ws):
        """
        验证模板结构是否符合预期
        
        检查关键列是否存在：
        - Row 4, Col 10 应包含 "Severity"
        - Row 4, Col 12 应包含 "Exposure"  
        - Row 4, Col 15 应包含 "Controllability"
        - Row 4, Col 17 应包含 "ASIL"
        """
        expected_checks = [
            (10, "Severity", "row4"),
            (12, "Exposure", "row4"),
            (15, "Controllability", "row4"),
            (17, "ASIL", "row4"),
            (11, "Rationale Severity", "row5"),
            (18, "SG-ID", "row5"),
            (19, "Safety Goal", "row5"),
        ]
        
        issues = []
        for col_idx, expected_substr, row_name in expected_checks:
            header_dict = self._header_row_4 if row_name == "row4" else self._header_row_5
            actual_header = header_dict.get(col_idx, "")
            actual_clean = actual_header.lower().replace(' ', '')
            expected_clean = expected_substr.lower().replace(' ', '')
            if expected_clean not in actual_clean and actual_clean not in expected_clean:
                issues.append(f"Col{col_idx} ({row_name}): expected '{expected_substr}', got '{actual_header}'")
        
        if issues:
            logger.warning(f"模板结构验证发现潜在问题: {issues}")
        else:
            logger.info("模板结构验证通过")
        
