    def _apply_draft_watermark(self, wb, quality_gate: Dict[str, Any]):
        warning_count = len(quality_gate.get("warnings", []))
        text = f"DRAFT / DIAGNOSTIC — 尚有{warning_count}项待评审，不得用于正式安全发布"
        for sheet_name in (self.HARA_SHEET_NAME, "06_Safety Goal"):
            if sheet_name not in wb.sheetnames:
                continue
            ws = wb[sheet_name]
            cell = ws["A1"] if sheet_name == self.HARA_SHEET_NAME else ws["A2"]
            cell.value = text
            cell.font = Font(name="Arial", size=12, bold=True, color="9C0006")
            cell.fill = PatternFill("solid", fgColor="FFF2CC")
            cell.alignment = Alignment(horizontal="center", vertical="center", wrap_text=True)
            # The template contains complex VW header/footer control codes.
            # Mutating oddHeader makes openpyxl rewrite those codes and Excel
            # repairs the worksheet on open. Keep the visible cell watermark
            # and preserve the template page header unchanged.
            page_setup_properties = ws.sheet_properties.pageSetUpPr
            if (
                page_setup_properties is not None
                and page_setup_properties.autoPageBreaks is None
                and page_setup_properties.fitToPage is None
            ):
                # openpyxl materializes an empty <pageSetUpPr/> while loading
                # these sheets. Excel rejects that rewritten sheetPr in this
                # template, so omit the empty node on save.
                ws.sheet_properties.pageSetUpPr = None

