def parse_arguments():
    """解析命令行参数"""
    parser = argparse.ArgumentParser(
        description="HARA报告生成器 - 支持从JSON数据源生成HARA报告"
    )

    parser.add_argument(
        "--template",
        type=str,
        default=None,
        help="模板Excel文件路径（默认使用HARA_Template_AI_20260327.xlsx）"
    )

    parser.add_argument(
        "--malfunction-json",
        type=str,
        default=None,
        help="malfunction_output.json文件路径"
    )

    parser.add_argument(
        "--scen-hazevent-json",
        type=str,
        default=None,
        help="scen_hazevent_output.json文件路径"
    )

    parser.add_argument(
        "--scoring-json",
        type=str,
        default=None,
        help="scoring_sg_output.json文件路径"
    )

    parser.add_argument(
        "--experience-json",
        type=str,
        default=None,
        help="经验库导出的JSON文件路径（experience_library_XX.json）"
    )

    parser.add_argument(
        "--output",
        type=str,
        required=True,
        help="输出Excel文件路径（必需）"
    )

    parser.add_argument(
        "--output-dir",
        type=str,
        default=None,
        help="摘要报告输出目录（可选）"
    )

    parser.add_argument(
        "--verbose",
        action="store_true",
        help="启用详细日志输出"
    )

    parser.add_argument(
        "--language",
        type=str,
        default="zh",
        choices=["zh", "en"],
        help="导出报告语言，zh=中文（默认），en=英语"
    )

    parser.add_argument(
        "--allow-draft",
        action="store_true",
        help="仅当正式质量门未通过但无结构性ERROR时，生成带DRAFT水印的诊断报告"
    )

    return parser.parse_args()


def main():
    """主函数入口"""
    args = parse_arguments()

    if args.verbose:
        logging.getLogger().setLevel(logging.DEBUG)

    try:
        generator = HARAReportGenerator(
            template_path=args.template,
            malfunction_json=args.malfunction_json,
            scen_hazevent_json=args.scen_hazevent_json,
            scoring_json=args.scoring_json,
            experience_json=args.experience_json,
            language=args.language,
            allow_draft=args.allow_draft,
        )

        context = generator._build_context_from_json()

        if not context.get("functions") and not args.experience_json:
            logger.warning("未从JSON数据源加载到功能数据，请检查JSON文件路径")

        result = generator.generate_hara_report(
            context=context,
            template_excel_path=args.template,
            output_excel_path=args.output,
            experience_json=args.experience_json,
            language=args.language
        )

        if result["success"]:
            logger.info(f"Excel报告生成成功: {result['output_path']}")
            print(f"成功: {result['message']}")
            print(f"输出文件: {result['output_path']}")

            if args.output_dir:
                summary_result = generator.generate_summary_report(context, args.output_dir)
                if summary_result["success"]:
                    logger.info("摘要报告生成成功")
                    print(f"HTML报告: {summary_result.get('html_report', '')}")
                    print(f"Markdown报告: {summary_result.get('markdown_report', '')}")
        else:
            logger.error(f"报告生成失败: {result.get('error', '未知错误')}")
            sys.exit(1)

    except FileNotFoundError as e:
        logger.error(f"文件不存在: {e}")
        sys.exit(1)
    except Exception as e:
        logger.error(f"执行失败: {e}")
        if args.verbose:
            import traceback
            traceback.print_exc()
        sys.exit(1)


if __name__ == "__main__":
    main()
