    def _load_experience_json(self, json_path: str) -> Dict[str, Any]:
        """加载经验库导出的JSON文件

        Args:
            json_path: experience_library_XX.json 路径

        Returns:
            解析后的JSON数据

        处理逻辑:
        1. 读取JSON文件
        2. 验证JSON格式完整性
        3. 提取05_HARA数据和06_Safety Goal数据
        4. 按照模板列标题映射到正确的列
        """
        if not os.path.exists(json_path):
            raise FileNotFoundError(
                f"经验库JSON文件不存在: {json_path}\n"
                f"请先运行 main_executor.py experience 导出经验库数据"
            )

        try:
            with open(json_path, 'r', encoding='utf-8') as f:
                data = json.load(f)
            logger.info(f"已加载经验库JSON: {json_path}")
        except json.JSONDecodeError as e:
            logger.error(f"JSON解析失败 {json_path}: {e}")
            return {}

        if not isinstance(data, dict):
            logger.warning(f"经验库JSON格式异常，期望dict类型，得到: {type(data)}")
            return {}

        hara_rows = data.get("05_HARA", []) or data.get("hara_data", [])
        sg_rows = data.get("06_Safety Goal", []) or data.get("safety_goals", [])
        template_matched = data.get("template_matched", {})

        if not hara_rows:
            logger.warning("经验库JSON中未找到05_HARA或hara_data数据")

        logger.info(f"经验库JSON包含: {len(hara_rows)} 条HARA记录, {len(sg_rows)} 条Safety Goal记录")

        return {
            "05_HARA": hara_rows,
            "06_Safety Goal": sg_rows,
            "template_matched": template_matched,
            "raw": data
        }

    def _load_json_file(self, file_path: str, expected_name: str) -> Dict[str, Any]:
        """加载单个JSON文件

        Args:
            file_path: JSON文件路径
            expected_name: 期望的文件名（用于错误提示）

        Returns:
            JSON数据字典

        Raises:
            FileNotFoundError: 文件不存在时给出友好提示
        """
        if not os.path.exists(file_path):
            engine_map = {
                "malfunction_output.json": "malfunction_engine.py",
                "scen_hazevent_output.json": "scen_hazevent_engine.py",
                "scoring_sg_output.json": "scoring_engine.py"
            }
            engine_script = engine_map.get(expected_name, "engine script")
            raise FileNotFoundError(
                f"JSON文件不存在: {file_path}\n"
                f"请先运行 {engine_script} 生成 {expected_name}"
            )

        try:
            with open(file_path, 'r', encoding='utf-8') as f:
                data = json.load(f)
            logger.info(f"已加载JSON数据: {file_path}")
            return data
        except json.JSONDecodeError as e:
            logger.error(f"JSON解析失败 {file_path}: {e}")
            return {}

    def _build_context_from_json(self) -> Dict[str, Any]:
        """从加载的JSON数据构建HARA上下文

        Returns:
            HARA分析上下文
        """
        context = {}

        if not any([self._malfunction_data, self._scen_hazevent_data, self._scoring_data]):
            logger.warning("没有加载任何JSON数据源")
            return context

        self._build_malfunction_context(context)
        self._build_scen_hazevent_context(context)
        self._build_scoring_context(context)

        return context

    def _build_malfunction_context(self, context: Dict[str, Any]):
        """从malfunction_output.json构建上下文

        数据映射:
        - B: Function <- functions
        - C: Output <- function_outputs
        - D: Guide-Word <- function_guidewords
        - E: Malfunction <- function_malfunctions
        - F: Hazard <- function_hazards
        """
        if not self._malfunction_data:
            return

        data = self._malfunction_data

        functions = data.get("functions", [])
        if not functions and "items" in data:
            functions = [item.get("function", "") for item in data.get("items", [])]

        function_outputs = data.get("function_outputs", {})
        function_guidewords = data.get("function_guidewords", {})
        function_malfunctions = data.get("function_malfunctions", {})
        function_hazards = data.get("function_hazards", {})

        if "items" in data:
            for item in data.get("items", []):
                func = item.get("function", "")
                if func and func not in functions:
                    functions.append(func)
                if "guidewords" in item:
                    function_guidewords[func] = item["guidewords"]
                if "malfunctions" in item:
                    function_malfunctions[func] = item["malfunctions"]
                if "hazards" in item:
                    function_hazards[func] = item["hazards"]

        context["functions"] = functions
        context["function_outputs"] = function_outputs
        context["function_guidewords"] = function_guidewords
        context["function_malfunctions"] = function_malfunctions
        context["function_hazards"] = function_hazards

        logger.info(f"malfunction上下文构建完成: {len(functions)} 个功能")

    def _build_scen_hazevent_context(self, context: Dict[str, Any]):
        """从scen_hazevent_output.json构建上下文

        数据映射:
        - G: Situational description <- function_scenarios (situational_description / scenario_summary)
        - H: Situational detailing <- function_scenarios (situational_detailing)
        - I: Hazardous event <- hazard_events

        JSON中function_scenarios[func]的key是string representations of dict，
        需要解析并提取malfunction字段作为新的key。

        同时将Step7的refined_function_scenarios合并到function_scenarios各条目中，
        补充 situational_description 和 situational_detailing 字段（见P2-5修复）。
        """
        if not self._scen_hazevent_data:
            return

        data = self._scen_hazevent_data

        raw_function_scenarios = data.get("function_scenarios", {})
        hazard_events = data.get("hazard_events", {})

        function_scenarios = {}
        for func, malf_dict in raw_function_scenarios.items():
            transformed = {}
            if isinstance(malf_dict, dict):
                for k, v in malf_dict.items():
                    malf_desc = self._extract_malfunction_from_key(k)
                    if malf_desc and v:
                        transformed[malf_desc] = v
            function_scenarios[func] = transformed

        if "items" in data:
            for item in data.get("items", []):
                func = item.get("function", "")
                if "scenarios" in item:
                    function_scenarios[func] = item["scenarios"]
                if "hazard_event" in item:
                    hazard_events[f"{func}_{item.get('guideword', '')}"] = item["hazard_event"]

        context["function_scenarios"] = function_scenarios
        context["hazard_events"] = hazard_events
        context["scenario_catalog"] = data.get("scenario_catalog", {})

        logger.info(f"scen_hazevent上下文构建完成: {len(function_scenarios)} 个场景")

    def _merge_refined_into_function_scenarios(
        self, function_scenarios: Dict, refined_function_scenarios: Dict
    ) -> Dict[str, Any]:
        """将 Step7 细化的场景字段合并到 function_scenarios 中。

        Step6 输出的 function_scenarios 包含 {scenario_summary, scenario, hazard_event, risk_level}。
        Step7 输出的 refined_function_scenarios 包含 {refined_scenario, original_scenario,
        vehicle_state, vehicle_speed, weather_conditions, road_surface_conditions, hazard_event}。

        合并后每条场景条目额外包含:
        - situational_description: Step7 的 refined_scenario（用于 G 列）
        - situational_detailing: 四个维度的组合（用于 H 列）
        """
        for func, malf_scenarios in function_scenarios.items():
            ref_malf_scenarios = refined_function_scenarios.get(func, {})
            for malf, scenarios in malf_scenarios.items():
                ref_scenarios = ref_malf_scenarios.get(malf, [])
                for sc in scenarios:
                    sc_main = str(sc.get("scenario_summary", "")).split("，")[0].strip()
                    for ref_sc in ref_scenarios:
                        orig = ref_sc.get("original_scenario", "")
                        if isinstance(orig, dict):
                            ref_main = orig.get("scenario", str(orig).split("，")[0].strip())
                        else:
                            ref_main = str(orig).split("，")[0].strip()
                        ref_main = ref_main.split("[")[0].strip()
                        if sc_main and sc_main == ref_main:
                            sc["situational_description"] = ref_sc.get(
                                "refined_scenario", sc.get("scenario_summary", "")
                            )
                            sc["situational_detailing"] = self._build_situational_detailing(ref_sc)
                            break
                    if "situational_description" not in sc:
                        sc["situational_description"] = sc.get("scenario_summary", "")
                        sc["situational_detailing"] = "N/A"
        return function_scenarios

    def _build_situational_detailing(self, ref_scenario: Dict) -> str:
        """从 Step7 细化场景构建 Situational Detailing 文本。

        组合 vehicle_state, vehicle_speed, weather_conditions, road_surface_conditions
        四个维度生成 Situational Detailing 描述。
        """
        parts = []
        for dim, label in [
            ("vehicle_state", "车辆状态"),
            ("vehicle_speed", "车速"),
            ("weather_conditions", "天气"),
            ("road_surface_conditions", "路面"),
        ]:
            val = ref_scenario.get(dim, "")
            if val and val != "N/A" and "all" not in str(val).lower():
                parts.append(f"{label}: {val}")
        return "；".join(parts) if parts else "N/A"

    @staticmethod
    def _scenario_fact(scenario: Dict[str, Any], key: str, default: Any = "") -> Any:
        """Read a scenario fact without changing the canonical Phase 2 payload."""
        if not isinstance(scenario, dict):
            return default
        value = scenario.get(key)
        if value not in (None, "", "N/A"):
            return value
        facts = scenario.get("scenario_facts", {})
        return facts.get(key, default) if isinstance(facts, dict) else default

    @staticmethod
    def _format_measurement(value: Any) -> str:
        if isinstance(value, float) and value.is_integer():
            return str(int(value))
        return str(value)

    def _compact_situational_description(self, scenario: Dict[str, Any]) -> str:
        """G列：按IAV风格简述天气、地点、动作、目标物和驾驶员状态。"""
        weather_raw = str(self._scenario_fact(scenario, "weather_conditions", ""))
        weather = "正常天气" if "正常" in weather_raw else weather_raw
        slope = str(self._scenario_fact(scenario, "slope", ""))
        location = "停车场坡道" if ("坡" in slope and "0%" not in slope) else "停车场"

        maneuver = str(self._scenario_fact(scenario, "maneuver", ""))
        direction = str(self._scenario_fact(scenario, "parking_direction", ""))
        if maneuver == "功能激活":
            action = "车辆静止，准备启动AVP"
        elif maneuver == "驻车保持":
            action = "泊车完成，车辆静止"
        elif maneuver == "安全静止":
            action = "车辆安全静止"
        else:
            action = direction or maneuver or "泊车"

        object_type = str(self._scenario_fact(scenario, "object_type", "周边目标物"))
        display_object_type = object_type.replace("接近车辆", "车辆")
        object_position = str(self._scenario_fact(scenario, "object_position", "车辆周边"))
        object_position = object_position.replace("车辆预计轨迹", "轨迹").replace("车辆泊车轨迹", "泊车轨迹")
        target_speed = self._scenario_fact(scenario, "target_speed_kph", None)
        motion_prefix = ""
        try:
            target_speed_value = float(target_speed)
            if 0 < target_speed_value <= 15:
                motion_prefix = "低速接近的"
            elif target_speed_value > 15:
                motion_prefix = "较高速度接近的"
        except (TypeError, ValueError):
            pass
        if "无近距离冲突" in display_object_type or display_object_type.lower() == "none":
            object_clause = "周边无近距离冲突目标"
        else:
            object_clause = f"{object_position}有{motion_prefix}{display_object_type}"

        driver_raw = str(self._scenario_fact(scenario, "driver_state", ""))
        if "已离车" in driver_raw:
            driver_clause = "驾驶员已离车"
        elif "车外" in driver_raw:
            driver_clause = "驾驶员在车外"
        else:
            driver_clause = driver_raw

        clauses = [weather, location, action, object_clause]
        if driver_clause:
            clauses.append(driver_clause)
        return "，".join(value for value in clauses if value) + "。"

    def _compact_situational_detailing(self, scenario: Dict[str, Any]) -> str:
        """H列：保留影响S/E/C的参数，采用IAV式短语而非键值模板。"""
        parts = []
        space = self._scenario_fact(scenario, "parking_space_type", "")
        if space:
            space = re.sub(r"（[^）]*）", "", str(space))
            parts.append(space)

        ego_speed = self._scenario_fact(scenario, "ego_speed_kph", None)
        if ego_speed is not None:
            parts.append(f"自车{self._format_measurement(ego_speed)} km/h")
        target_speed = self._scenario_fact(scenario, "target_speed_kph", None)
        if target_speed is not None:
            parts.append(f"目标{self._format_measurement(target_speed)} km/h")
        relative_speed = self._scenario_fact(scenario, "relative_speed_kph", None)
        if relative_speed is not None:
            parts.append(f"相对{self._format_measurement(relative_speed)} km/h")
        acceleration = self._scenario_fact(scenario, "longitudinal_acceleration_mps2", None)
        if acceleration not in (None, 0, 0.0, "0", "0.0"):
            parts.append(f"纵向加速度{self._format_measurement(acceleration)} m/s²")

        distance = self._scenario_fact(scenario, "relative_distance", "")
        if distance:
            parts.append(f"距离{distance}")
        slope = self._scenario_fact(scenario, "slope", "")
        if slope:
            parts.append(f"坡度{slope}")
        road = str(self._scenario_fact(scenario, "road_surface_conditions", ""))
        if road:
            road = road.replace("停车场", "").replace("路面", "").replace("（", "").replace("）", "")
            road = road.replace("铺装干燥或潮湿", "铺装干/湿")
            parts.append(f"{road}路面")

        steering_error = self._scenario_fact(scenario, "steering_control_error_deg", None)
        if steering_error is not None:
            parts.append(f"转向误差{self._format_measurement(steering_error)}°")
            if self._scenario_fact(scenario, "steering_angle_deg", None) is None:
                parts.append("目标转角未定义")
        return "，".join(parts) if parts else "N/A"

    @staticmethod
    def _compact_hazard_event(hazard_event: Any) -> str:
        """I列：仅保留车辆层危害和伤害，去掉与失效列重复的模板前缀。"""
        text = re.sub(r"\s+", " ", str(hazard_event or "")).strip()
        bracket_parts = [part.strip(" ，。；") for part in re.findall(r"<([^>]*)>", text)]
        if len(bracket_parts) >= 3:
            behavior = re.sub(r"（相对速度约[^）]*）", "", bracket_parts[1])
            behavior = re.split(r"并接近位于|并接近|，接近", behavior, maxsplit=1)[0]
            behavior = behavior.replace("车辆在泊车轨迹中", "车辆")
            behavior = behavior.replace(
                "后续车辆或近距离人员来不及避让", "周边交通参与者可能无法避让"
            )
            harm = re.split(r"；驾驶员位于车外|；异常", bracket_parts[2], maxsplit=1)[0]
            return f"{behavior}；{harm}。"
        text = text.replace(">导致<", "，导致").replace("<", "").replace(">", "")
        return text if text.endswith("。") else text + "。"

    def _compact_severity_reason(self, result: Dict[str, Any], scenario: Dict[str, Any],
                                 hazard_event: str) -> str:
        score = str(result.get("severity_score", "N/A"))
        if score == "S0":
            return "无可预见人员伤害 → S0。"
        relative_speed = self._scenario_fact(scenario, "relative_speed_kph", None)
        object_type = str(self._scenario_fact(scenario, "object_type", "道路使用者"))
        object_type = object_type.replace("儿童行人", "行人").replace("接近车辆", "车辆")
        harm = {
            "S0": "无可预见人员伤害", "S1": "预计轻中度伤害",
            "S2": "预计严重且可能危及生命的伤害", "S3": "预计危及生命或致命伤害",
        }.get(score, "按伤害程度评估")
        evidence = []
        if relative_speed not in (None, 0, 0.0, "0", "0.0"):
            evidence.append(f"相对速度约{self._format_measurement(relative_speed)} km/h")
        if object_type:
            evidence.append(f"涉及{object_type}")
        if "失稳" in hazard_event:
            evidence.append("存在车辆失稳")
        evidence.append(harm)
        return f"{'，'.join(evidence)} → {score}。"

